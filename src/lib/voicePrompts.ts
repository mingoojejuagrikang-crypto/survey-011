/** v0.36.0 FB#4(Vance) — 음성 안내(TTS)와 화면 재질문 큐가 공유하는 프롬프트의 SSOT.
 *  소수점 유실 재질문 문구가 종전엔 세 콜사이트에 인라인 리터럴로 흩어져 있어(useVoiceSession)
 *  TTS로만 나가고 화면엔 없었다. 여기 한 곳으로 모아 say()와 ReaskCue가 같은 상수를 공유한다.
 *
 * ─────────────────────────────────────────────────────────────────────────────────
 * 🔴 **v0.49 r2 W2 계약 개정(민구 2026-08-13) — TTS본과 화면본은 더 이상 같지 않다.**
 *
 * 민구 원문: *"이번에 TTS와 화면 문구는 일치하지 않을거야. 음성안내를 가능하면 축약해서 업무
 * 속도를 올리고 싶거든."*
 *
 * 배경: 이 앱의 사용자는 폰을 2~3m 떨어뜨려 놓고 장갑 낀 손으로 일한다 — **화면은 자주 못 보고
 * 귀만 열려 있다.** 그래서 긴 TTS는 그대로 대기 시간이고, [TTS-WATCHDOG-1]에서 긴 발화일수록
 * 절단률이 단조 증가하기까지 한다. 반면 화면은 눈이 갔을 때 정보가 많을수록 낫다.
 *
 * 그래서 PRINCIPLES §2는 「글자까지 일치」가 아니라 **「의미 동등 + 구조적 분리」**다:
 *   · **의미 동등** — 두 표면이 같은 사실을 말한다. 한쪽만 아는 상태가 있으면 안 된다.
 *   · **구조적 분리** — 분리는 **이 파일의 쌍 상수로만** 한다. 콜사이트에 인라인 리터럴을
 *     흩뿌리는 방식으로 갈라놓으면 v0.36.0 이전으로 되돌아간다(그때 화면과 TTS가 조용히 어긋났다).
 *
 * 이름 규칙: `*_TTS` = 귀로 나가는 축약본 · `*_SCREEN` = 눈으로 보는 상세본.
 * ───────────────────────────────────────────────────────────────────────────────── */

/** 소수부 타깃 재질문 — **TTS·화면 공용**(이 문구는 개정 대상이 아니다, 확정표 #3 「현행 유지」).
 *  분리하지 않은 이유: 축약할 여지가 없고, 정수부 문맥을 양쪽이 똑같이 말해야 한다. */
export function decimalReaskPrompt(whole: string | number): string {
  return `${whole} 점, 소수점 아래 숫자만 말씀해 주세요.`;
}

/** 재질문 사유 2버킷 — **화면본**(`ReaskCue`). v0.48.0 P3 이후로 TTS도 이걸 읽었으나,
 *  W2 개정으로 TTS는 아래 `REASK_TTS`로 갈라졌다. 화면 문구 자체는 **불변**이다. */
export const REASK_SCREEN: Record<'low_confidence' | 'parse_failed', string> = {
  low_confidence: '소리가 불확실',
  parse_failed: '숫자로 인식 실패',
};

/** 재질문 사유 2버킷 — **TTS본**(확정표 #1·#2, 민구 08-13 확정. 바이트 그대로).
 *
 *  🔴 **꼬리를 되살리지 마라.** 종전엔 `"{사유}. 잘 못 들었습니다. {항목} 다시 말씀해 주세요."`
 *  였다. 재질문 지시("다시 말씀해 주세요")가 사라진 자리는 **부정 비프 + 화면 `ReaskCue`**가
 *  전담한다 — 사용자는 이미 그 셀에 답하는 중이고, 무엇을 하라는지는 비프가 말한다.
 *  화면 상세는 `REASK_SCREEN`이 그대로 들고 있다(의미 동등). */
export const REASK_TTS: Record<'low_confidence' | 'parse_failed', string> = {
  low_confidence: '소리가 불확실.',
  parse_failed: '숫자로 인식 실패.',
};

/** 완료 행 검토 대기(reviewWait)에서 bare 값을 흡수했을 때의 안내 — **TTS본**(확정표 #4).
 *  종전: `"{N}행은 완료된 행입니다. 수정하려면 '수정', 다음 행은 '다음행'이라고 말씀해 주세요."`
 *  두 진입로('수정'·'다음행')를 **어휘만** 남겨 절반 이하로 줄였다 — 그 두 단어가 실제로 먹히는
 *  명령이라는 점이 이 문구의 핵심이고(fix49b #8), 설명은 도움말이 맡는다. */
export function reviewWaitAbsorbTts(row: number): string {
  return `${row}행 완료됨. 수정 또는 다음행.`;
}

/** 끝 도달 안내 — **TTS본**(확정표 #5+6 통합). 종전엔 트리거 2개가 **서로 다른 문구**를 썼다:
 *  ⓐ `announceEndReached` "마지막 행까지 입력했습니다… 종료하려면 '종료'라고 말씀하거나…"
 *  ⓑ atEnd 값 흡수 "입력이 끝났습니다. 종료하려면…"
 *  같은 상태를 두 이름으로 부르면 사용자는 두 상태가 있는 줄 안다 — 하나로 합치고, 대신
 *  **이번 세션에 몇 행을 끝냈는지**를 말한다(민구 확정: 종료 안내 꼬리보다 그 숫자가 쓸모 있다.
 *  종료 수단은 화면 하단 ⏹과 '종료' 명령으로 이미 상시 노출된다).
 *
 *  @param completedRows 완료 행 수 — **화면 `X / N`의 X와 같은 값**(`completedRows.length`)을
 *    넘겨라. 두 표면이 다른 숫자를 말하면 그게 §2 위반이다.
 *  @param emptyRowsPhrase `formatRowList(빈 행들)` 결과. 빈 행이 없으면 null — 꼬리 자체가 빠진다. */
export function endReachedTts(completedRows: number, emptyRowsPhrase: string | null): string {
  const head = `마지막행 입력. 이번 세션에 완료된 행은 ${completedRows}행.`;
  return emptyRowsPhrase ? `${head} ${emptyRowsPhrase}이 비어 있습니다.` : head;
}
