/**
 * 🔴 v0.49 r4 M11(민구 D2 08-13 · codex r3 F8) — **같은 셀을 다시 듣겠다**는 재청취 안내.
 *
 * 이 한 문장이 네 콜사이트에 **인라인 리터럴**로 복제돼 있었다(`useVoiceSession`의
 * `cmdModify` 재수정 · `cmdCancel` · `modifyAnomalyTouch` · 저신뢰 명령 거절).
 * §2가 금지하는 형태 그대로다 — *"구조적 분리는 **이 파일의 쌍 상수로만**"*. 사본이 넷이면
 * 확정표가 다음에 이 문구를 손볼 때 **어느 하나가 조용히 남는다**([PAST-2] 형태).
 *
 * ⚠️ **바이트는 그대로 옮긴다.** W2가 지운 것은 「거절 사유 뒤에 붙던 꼬리」이고, 이 문장은
 * 거절이 아니라 **재청취 국면의 안내**다(사용자 입력은 접수됐고 앱이 같은 칸을 다시 듣는다).
 * 두 상황을 같은 개정으로 묶지 않는다.
 *
 * 화면본을 따로 두지 않는 이유: 이 국면의 화면은 수정 표시(`ModifyIndicatorPill`)와
 * 활성 칩이 이미 「이 칸을 다시 받는 중」을 그린다 — 같은 말을 문장으로 또 쓰지 않는다.
 */
export function relistenPrompt(name: string): string {
  return `${name} 다시 말씀해 주세요.`;
}

/** 완료 행 검토 대기(reviewWait)에서 bare 값을 흡수했을 때의 안내 — **TTS본**(확정표 #4).
 *  종전: `"{N}행은 완료된 행입니다. 수정하려면 '수정', 다음 행은 '다음행'이라고 말씀해 주세요."`
 *  두 진입로('수정'·'다음행')를 **어휘만** 남겨 절반 이하로 줄였다 — 그 두 단어가 실제로 먹히는
 *  명령이라는 점이 이 문구의 핵심이고(fix49b #8), 설명은 도움말이 맡는다. */
/** 🔴 v0.49 r6 Y5(claude #4 · codex R5-F3) — 검토 대기에서 **실제로 먹히는 조작 어휘**.
 *  흡수 안내와 저신뢰 **명령** 거절의 꼬리가 이 하나를 공유한다. 두 표면이 같은 상태를
 *  가리키므로 문구도 하나여야 한다(cellWaitPrompt가 세운 *"같은 상태에 두 이름을 주지 않는다"*
 *  와 같은 계약). 종전 거절 꼬리는 `relistenPrompt`(= "{항목} 다시 말씀해 주세요")여서
 *  **이 상태에서 받을 수 없는 값**을 요구했다 — 시킨 대로 하면 흡수 안내가 되받는다.
 *  ⚠️ 늘리지 마라([TTS-WATCHDOG-1] 긴 발화일수록 절단률이 단조 증가). */
export const REVIEW_WAIT_COMMANDS_TTS = '수정 또는 다음행.';

export function reviewWaitAbsorbTts(row: number): string {
  return `${row}행 완료됨. ${REVIEW_WAIT_COMMANDS_TTS}`;
}

/** 끝 도달 안내 — **TTS본**(확정표 #5+6 통합). 종전엔 트리거 2개가 **서로 다른 문구**를 썼다:
 *  ⓐ `announceEndReached` "마지막 행까지 입력했습니다… 종료하려면 '종료'라고 말씀하거나…"
 *  ⓑ atEnd 값 흡수 "입력이 끝났습니다. 종료하려면…"
 *  같은 상태를 두 이름으로 부르면 사용자는 두 상태가 있는 줄 안다 — 하나로 합치고, 대신
 *  **이번 세션에 몇 행을 끝냈는지**를 말한다(민구 확정: 종료 안내 꼬리보다 그 숫자가 쓸모 있다.
 *  종료 수단은 화면 하단 ⏹과 '종료' 명령으로 이미 상시 노출된다).
 *
 *  @param completedRows 완료 행 수 — **화면 `X / N`의 X와 같은 값**(`completedRows.length`)을
 *    넘겨라. 두 표면이 다른 숫자를 말하면 그게 §2 위반이다.
 *  @param emptyRowsPhrase `formatRowList(빈 행들)` 결과. 빈 행이 없으면 null — 꼬리 자체가 빠진다. */
export function endReachedTts(completedRows: number, emptyRowsPhrase: string | null): string {
  const head = `마지막행 입력. 이번 세션에 완료된 행은 ${completedRows}행.`;
  return emptyRowsPhrase ? `${head} ${emptyRowsPhrase}이 비어 있습니다.` : head;
}
